// HOST=0.0.0.0); the default stays local.
const HOST = process.env.HOST || '127.0.0.1';
const server = app.listen(PORT, HOST, () => {
  const url = `http://${HOST}:${PORT}`;
  origLog(`\n📮 md-publisher GUI`);
  origLog(`   地址: ${url}`);
  if (HOST !== '127.0.0.1' && HOST !== '::1' && HOST !== 'localhost') {
    origLog(`   ⚠ 已监听所有网络接口 (${HOST})，同网络下的设备可直接访问此接口`);
  }
  origLog(`   按 Ctrl+C 退出\n`);

  // Auto-open browser (skip if NO_OPEN env is set — set by Electron shell)
  if (!process.env.NO_OPEN) {
    openBrowser(url);
  }

  // When launched as an Electron utilityProcess child, tell the main process
  // we're up and accept a shutdown request (quit Chrome, then exit).
  attachForkBridge({
    parentPort: process.parentPort,
    port: PORT,
    token: HANDSHAKE_TOKEN,
    onShutdown: () => {
      origLog('\n📮 收到关闭指令，正在退出...');
      for (const res of sseClients) { res.end(); }
      sseClients.clear();
      server.close();
      const forceExit = setTimeout(() => process.exit(0), 3000);
      closeContext().catch(() => {}).finally(() => { clearTimeout(forceExit); process.exit(0); });
    },
  });
});

// --- Graceful shutdown on SIGINT/SIGTERM ---
let _shuttingDown = false;
function gracefulShutdown(signal) {
  if (_shuttingDown) return;
  _shuttingDown = true;
  origLog(`\n📮 收到 ${signal}，正在关闭...`);
  // End all SSE connections so server.close() can finish quickly
  for (const res of sseClients) { res.end(); }
  sseClients.clear();
  server.close();
  const forceExit = setTimeout(() => process.exit(0), 3000);
  // Disconnect (not close): leave Chrome running so a Ctrl+C / crash / closed
  // terminal doesn't kill the browser — the next launch reconnects to it.
  disconnectContext().catch(() => {}).finally(() => { clearTimeout(forceExit); process.exit(0); });
}
process.on('SIGINT', () => gracefulShutdown('SIGINT'));
process.on('SIGTERM', () => gracefulShutdown('SIGTERM'));
process.on('unhandledRejection', (reason) => {
  origError(`\n未处理的异步错误: ${reason}`);
  gracefulShutdown('unhandledRejection');
});

server.on('error', (err) => {
  if (err.code === 'EADDRINUSE') {
    origError(`\n❌ 端口 ${PORT} 已被占用`);
    origError(`   可能已有一个 md-publisher 实例正在运行`);
    origError(`   请关闭后重试，或使用 PORT=其他端口 node src/gui.js\n`);
  } else {
    origError(`\n❌ 服务器启动失败: ${err.message}\n`);
  }
  process.exit(1);
});
