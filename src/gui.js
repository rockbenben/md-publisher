// --- Cross-origin guard for the API ---
// This API has no auth: it can browse the filesystem, publish drafts, drive the
// logged-in Chrome and shut the app down. Even bound to loopback, any page the
// user visits can fire a "simple" cross-origin POST (`mode:'no-cors'`, no
// preflight) at http://127.0.0.1:9870/api/shutdown and the browser will happily
// deliver it. Browsers always attach Origin to such requests, so rejecting
// non-local origins closes that drive-by hole. Requests with no Origin (curl,
// the Electron main process, a health probe) are same-machine and pass through.
const LOCAL_ORIGINS = new Set([
  '127.0.0.1', 'localhost', '[::1]', '::1',
]);
function isLocalOrigin(origin) {
  try {
    const { hostname } = new URL(origin);
    return LOCAL_ORIGINS.has(hostname.toLowerCase());
  } catch {
    return false;
  }
}
app.use('/api', (req, res, next) => {
  const origin = req.headers.origin;
  if (origin && !isLocalOrigin(origin)) {
    origError(`⚠ 拒绝跨源请求: ${req.method} ${req.originalUrl} (Origin: ${origin})`);
    return res.status(403).json({ error: '拒绝跨源请求' });
  }
  next();
});

