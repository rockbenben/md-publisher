// GET /api/articles — scan directory for articles (async to avoid blocking event loop)
app.get('/api/articles', asyncHandler(async (req, res) => {
  const settings = loadSettings();
  const dir = req.query.dir || settings.articleDir;

  if (!dir) {
    return res.json({ articles: [], dir: '' });
  }

  const absDir = resolve(dir);

  try {
    await fsAccess(absDir);
  } catch {
    return res.json({ articles: [], error: `目录不存在: ${absDir}` });
  }

  try {
    const skipped = [];
    const [articles, projectConfig] = await Promise.all([
      scanArticleDirAsync(absDir, {
        recursive: true,
        onSkip: (item) => skipped.push(item),
      }),
      loadProjectConfigAsync(absDir),
    ]);
    res.json({
      articles: articles.map((a) => {
        const ext = extname(a.filePath);
        const rel = relative(absDir, a.filePath);
        return {
          title: a.meta.title || basename(a.filePath, ext),
          description: a.meta.description || '',
          date: a.meta.date || '',
          cover: a.meta.cover || '',
          filePath: a.filePath,
          fileName: basename(a.filePath),
          relativePath: rel && !rel.startsWith('..') && !isAbsolute(rel)
            ? rel.split(sep).join('/')
            : '',
        };
      }),
      dir: absDir,
      projectConfig: projectConfig || undefined,
      skipped,
    });
  } catch (err) {
    res.status(500).json({ articles: [], error: `扫描目录失败: ${err.message}` });
  }
}));

// POST /api/articles/parse — parse a single file path (for manual add)
app.post('/api/articles/parse', asyncHandler(async (req, res) => {
  const { filePath } = req.body;
  if (!filePath) {
    return res.status(400).json({ error: '请提供文件路径' });
  }

  const absPath = resolve(filePath);

  let s;
  try {
    s = await fsStat(absPath);
  } catch {
    return res.status(400).json({ error: `文件不存在: ${absPath}` });
  }

  // If it's a directory, scan it
  if (s.isDirectory()) {
    const skipped = [];
    const articles = await scanArticleDirAsync(absPath, {
      recursive: true,
      onSkip: (item) => skipped.push(item),
    });
    if (articles.length === 0) {
      const detail = skipped.length
        ? `（${skipped.map((s) => s.fileName).join('、')} 无法解析）`
        : '';
      return res.status(400).json({
        error: `目录下没有可解析的文章文件${detail}`,
        skipped,
      });
    }
    return res.json({
      articles: articles.map((a) => {
        const ext = extname(a.filePath);
        return {
          title: a.meta.title || basename(a.filePath, ext),
          description: a.meta.description || '',
          date: a.meta.date || '',
          cover: a.meta.cover || '',
          filePath: a.filePath,
          fileName: basename(a.filePath),
          manual: true,
        };
      }),
      skipped,
    });
  }

  // Single file
  try {
    const article = await parseArticleAsync(absPath);
    const ext = extname(absPath);
    res.json({
      articles: [{
        title: article.meta.title || basename(absPath, ext),
        description: article.meta.description || '',
        date: article.meta.date || '',
        cover: article.meta.cover || '',
        filePath: absPath,
        fileName: basename(absPath),
        manual: true,
      }],
    });
  } catch (err) {
    const reason = String(err?.message || err).split(/\r?\n/)[0].slice(0, 240);
    res.status(400).json({ error: `解析失败: ${reason}` });
  }
}));

// POST /api/articles/upload — accept file content from browser <input type="file">
// Writes file to .uploads/ (needed by publish step), but parses in-memory
// to avoid the redundant readFileSync round-trip during upload.
app.post('/api/articles/upload', asyncHandler(async (req, res) => {
  const { files } = req.body; // [{ name, content }]
  if (!files?.length) return res.status(400).json({ error: '没有文件' });
  if (files.length > 100) return res.status(400).json({ error: `文件数量超出限制 (${files.length}/100)` });
  await mkdir(UPLOAD_DIR, { recursive: true });
  const articles = [];
  const skipped = [];
  // Mirrors MAX_FILE_SIZE in web/src/lib/filePicker.ts — the browser checks it
  // first so the user is told before uploading, and this catches a direct POST
  // that skipped the UI. Keep the two in step.
  const MAX_FILE_SIZE = 10 * 1024 * 1024; // 10MB per file
  for (const f of files) {
    try {
      // Server-side size check (frontend also checks, but direct POST could bypass)
      if (typeof f.content !== 'string' || f.content.length > MAX_FILE_SIZE) {
        origLog(`⚠ 跳过过大或无效的文件: ${f.name}`);
        skipped.push({ fileName: f.name, reason: '文件过大或内容无效' });
        continue;
      }
      let safeName = sanitizeUploadFileName(f.name);
      // Skip files with unsupported extensions
      if (!ARTICLE_EXTS.has(extname(safeName).toLowerCase())) {
        origLog(`⚠ 跳过不支持的文件类型: ${f.name}`);
        skipped.push({ fileName: f.name, reason: '不支持的文件类型' });
        continue;
      }
      let tmpPath = resolve(UPLOAD_DIR, safeName);
      if (!isPathWithin(tmpPath, UPLOAD_DIR)) {
        origLog(`⚠ 跳过非法文件名: ${f.name}`);
        skipped.push({ fileName: f.name, reason: '文件名不合法' });
        continue;
      }
      // Disambiguate distinct files that share a basename (e.g. Hugo-style page
      // bundles where every post is index.md). Without this the second file
      // overwrites the first on disk AND collides on filePath, so the frontend
      // dedups them to one row — silently dropping all but the last. Identical
      // re-uploads keep the same name so they still dedup cleanly.
      const stem = basename(safeName, extname(safeName));
      const stemExt = extname(safeName);
      let dup = 1;
      // Compare sizes before contents: a sync readFileSync of every existing
      // candidate blocked the event loop (and with it the SSE heartbeat) for up
      // to 10MB per file per collision. `await readFile` keeps the loop free.
      for (;;) {
        let collides = false;
        try {
          const st = await fsStat(tmpPath);
          collides = st.size !== Buffer.byteLength(f.content, 'utf-8')
            || (await readFile(tmpPath, 'utf-8')) !== f.content;
        } catch {
          collides = false; // nothing on disk at this path — the slot is free
        }
        if (!collides) break;
        safeName = `${stem}-${dup}${stemExt}`;
        tmpPath = resolve(UPLOAD_DIR, safeName);
        dup++;
      }
      await writeFile(tmpPath, f.content, 'utf-8');
      // Parse in memory — skip the redundant readFileSync in parseArticle()
      const article = parseArticleString(f.content, tmpPath);
      const ext = extname(tmpPath);
      articles.push({
        title: article.meta.title || basename(tmpPath, ext),
        description: article.meta.description || '',
        date: article.meta.date || '',
        cover: article.meta.cover || '',
        filePath: tmpPath,
        fileName: f.name,
        manual: true,
      });
    } catch (err) {
      const reason = String(err?.message || err).split(/\r?\n/)[0].slice(0, 240);
      origLog(`⚠ 跳过无法解析的文件: ${f.name} — ${err?.message || err}`);
      skipped.push({ fileName: f.name, reason });
    }
  }
  res.json({ articles, skipped });
}));

// GET /api/browse-dir — list subdirectories (for web-based directory browser)
app.get('/api/browse-dir', asyncHandler(async (req, res) => {
  const dir = req.query.path || '';
  if (!dir) {
    // List drives on Windows, root on others
    if (process.platform === 'win32') {
      const drives = [];
      for (let i = 65; i <= 90; i++) {
        const d = String.fromCharCode(i) + ':\\';
        try { await fsAccess(d); drives.push({ name: d, path: d }); } catch {}
      }
      return res.json({ entries: drives, current: '' });
    }
    return res.json({ entries: [{ name: '/', path: '/' }], current: '' });
  }
  try {
    const absDir = resolve(dir);
    const dirents = await readdir(absDir, { withFileTypes: true });
    const entries = dirents
      .filter(d => d.isDirectory() && !d.name.startsWith('.') && !d.name.startsWith('$'))
      .map(d => ({ name: d.name, path: resolve(absDir, d.name) }))
      .sort((a, b) => a.name.localeCompare(b.name));
    const parent = resolve(absDir, '..');
    res.json({ entries, current: absDir, parent: parent !== absDir ? parent : '' });
  } catch (err) {
    res.status(400).json({ error: err.message, entries: [], current: dir });
  }
}));

// POST /api/publish — start publishing
app.post('/api/publish', asyncHandler(async (req, res) => {
  const { filePaths, platforms, category, tag, autoCover, removeCoverImg } = req.body;

  if (isPublishing) {
    return res.status(409).json({ error: '已有发布任务正在进行' });
  }

  if (!filePaths?.length || !platforms?.length) {
    return res.status(400).json({ error: '请选择文章和平台' });
  }

  // Reject malformed paths up front — a non-string here would later throw in
  // basename() *after* the lock is taken, leaking isPublishing forever.
  if (!Array.isArray(filePaths) || !filePaths.every(fp => typeof fp === 'string')) {
    return res.status(400).json({ error: '文件路径无效' });
  }

  // Validate and sort platform IDs to match config order
  const validPlatformIds = orderedValidPlatforms(platforms, Object.keys(PLATFORMS), Object.keys(platformPublishers));
  if (validPlatformIds.length === 0) {
    return res.status(400).json({ error: '没有有效的平台' });
  }

  // Lock BEFORE async parsing to prevent concurrent requests slipping through.
  // Create the AbortController synchronously here too, so a cancel request that
  // arrives during the parse window below can actually abort the task.
  isPublishing = true;
  publishAbort = new AbortController();
  broadcast('status', { publishing: true });

  // Parse articles (async to avoid blocking event loop) — collect ALL errors before aborting
  const articles = [];
  const parseErrors = [];
  for (const fp of filePaths) {
    try {
      articles.push(await parseArticleAsync(fp));
    } catch (err) {
      parseErrors.push(`${basename(fp)}: ${err.message}`);
    }
  }
  if (parseErrors.length > 0) {
    isPublishing = false;
    publishAbort = null;
    const errMsg = `解析文件失败:\n${parseErrors.join('\n')}`;
    broadcast('status', { publishing: false });
    broadcast('app-error', { message: errMsg });
    return res.status(400).json({ error: errMsg });
  }

  // Cancelled while parsing — bail out before launching the publish task
  if (publishAbort.signal.aborted) {
    isPublishing = false;
    publishAbort = null;
    broadcast('cancelled', {});
    broadcast('status', { publishing: false });
    return res.json({ status: 'cancelled' });
  }

  // Respond immediately — actual publishing happens async
  res.json({ status: 'started', articleCount: articles.length, platformCount: validPlatformIds.length });

  // Run publishing in the background. No promise handle is kept: the lock is
  // `isPublishing` (reset by publishArticles' try/finally), and the .catch()
  // below means an un-awaited rejection can never escape.
  publishArticles(articles, validPlatformIds, { category, tag, autoCover: autoCover === true, removeCoverImg: !!removeCoverImg }, publishAbort.signal)
    .catch((err) => {
      broadcast('app-error', { message: err?.message || String(err) });
    })
    .finally(() => { publishAbort = null; });
}));

// POST /api/cancel-publish — cancel the current publish task
app.post('/api/cancel-publish', (req, res) => {
  if (!isPublishing || !publishAbort) {
    return res.status(400).json({ error: '没有正在进行的发布任务' });
  }
  // The publish signal is only checked between platforms. A login wait can
  // last up to five minutes, so interrupt that wait directly as well.
  abortLoginWait();
  publishAbort.abort();
  res.json({ ok: true });
});

