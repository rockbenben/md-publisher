// `checkUpdates` is the opt-in for the background update check the main
// process runs at startup. Off by default: the app makes no request at all
// until the user asks for it in Settings.
const DEFAULT_SETTINGS = { articleDir: '', defaultPlatforms: ['sspai', 'zhihu', 'wechat'], checkUpdates: false };

// Memory cache — avoids readFileSync on every request
let _settingsCache = null;

function loadSettings() {
  if (!_settingsCache) {
    try {
      if (existsSync(SETTINGS_FILE)) {
        const raw = readFileSync(SETTINGS_FILE, 'utf-8');
        const parsed = JSON.parse(raw);
        // Validate structure — must be a plain object
        if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
          origError('⚠ settings.json 格式异常，已重置为默认设置');
          _settingsCache = { ...DEFAULT_SETTINGS };
        } else {
          _settingsCache = { ...DEFAULT_SETTINGS, ...parsed };
        }
      }
    } catch (err) {
      origError(`⚠ settings.json 读取失败: ${err.message}，使用默认设置`);
    }
    if (!_settingsCache) _settingsCache = { ...DEFAULT_SETTINGS };
  }
  // Return a shallow copy so callers don't accidentally mutate the cache
  return { ..._settingsCache };
}

async function saveSettings(settings) {
  try {
    await writeFile(SETTINGS_FILE, JSON.stringify(settings, null, 2), 'utf-8');
    _settingsCache = { ...settings }; // Update cache on successful write
  } catch (err) {
    _settingsCache = null; // Invalidate cache on write failure
    origError(`⚠ settings.json 保存失败: ${err.message}`);
    throw err;
  }
}

// Serialize settings writes. Both the settings route and the login-status
// persist do read-modify-write on the whole settings object; running them
// concurrently let the later writer clobber the other's field with a stale
// snapshot. Chaining ensures each mutator reads the freshest cache (updated by
// the prior saveSettings) inside its own turn. The tail swallows rejections so
// one failed write can't wedge the chain.
// Contract: `mutator(settings)` returns the full settings object to persist.
let _settingsTail = Promise.resolve();
function updateSettings(mutator) {
  const result = _settingsTail.then(async () => {
    const next = await mutator(loadSettings());
    await saveSettings(next);
    return next;
  });
  _settingsTail = result.then(() => {}, () => {});
  return result;
}

// --- SSE clients ---
const sseClients = new Set();
// A client that reloads during a five-minute login wait must still see what the
// run is waiting for; replay the latest notice in the initial SSE snapshot.
let lastLoginWait = null;

function broadcast(event, data) {
  if (sseClients.size === 0) return; // Skip serialization when no clients
  const msg = `event: ${event}\ndata: ${JSON.stringify(data)}\n\n`;
  for (const res of sseClients) {
    if (res.writableEnded || res.destroyed) {
      sseClients.delete(res);
      continue;
    }
    try {
      res.write(msg);
    } catch {
      sseClients.delete(res);
    }
  }
}

// Log lines are easy to miss: the progress banner is what the user is looking
// at. Surface the login wait there as a dedicated event.
setNoticeHandler((notice) => {
  lastLoginWait = notice.status === 'waiting' ? notice : null;
  broadcast('login-wait', notice);
});

// Clean up stale uploaded files on startup (older than 24h)
(async () => {
  try {
    const entries = await readdir(UPLOAD_DIR).catch(() => []);
    const cutoff = Date.now() - 24 * 60 * 60 * 1000;
    for (const name of entries) {
      const fp = resolve(UPLOAD_DIR, name);
      try {
        const s = await fsStat(fp);
        if (s.isFile() && s.mtimeMs < cutoff) await unlink(fp);
      } catch {}
    }
  } catch {}
})();

// Redirect console.log to also broadcast to SSE clients
const origLog = console.log;
const origError = console.error;

console.log = (...args) => {
  origLog(...args);
  const text = stripAnsi(args.map(safeStringify).join(' '));
  if (text.trim()) broadcast('log', { text });
};

console.error = (...args) => {
  origError(...args);
  const text = stripAnsi(args.map(safeStringify).join(' '));
  if (text.trim()) broadcast('log', { text, level: 'error' });
};

// --- Publishing state ---
// `isPublishing` is the real lock: /api/publish sets it synchronously before any
// await, so a second request cannot slip past while the first is still parsing.
// publishArticles' try/finally guarantees it is cleared again.
let isPublishing = false;
let publishAbort = null; // AbortController for current publish task

async function publishArticles(articles, platformIds, options = {}, signal = null) {
  // isPublishing is already set by the caller (route handler) to prevent race conditions
  const allResults = [];
  let cancelled = false;
  // A platform whose login timed out will not recover during this run. Waiting
  // five minutes again for every later article turns a big batch into hours.
  const loginFailed = new Set();

  try {
    for (let i = 0; i < articles.length; i++) {
      if (signal?.aborted) { cancelled = true; broadcast('cancelled', {}); break; }

      const article = articles[i];

      broadcast('progress', {
        articleIndex: i,
        articleCount: articles.length,
        title: article.meta.title || basename(article.filePath, extname(article.filePath)),
      });

      for (const platformId of platformIds) {
        if (signal?.aborted) { cancelled = true; broadcast('cancelled', {}); break; }

        const publishFn = platformPublishers[platformId];
        if (!publishFn) continue;
        if (loginFailed.has(platformId)) {
          allResults.push({
            success: false,
            platform: PLATFORMS[platformId].name,
            message: '登录未完成，本次已跳过',
          });
          continue;
        }

        broadcast('platform', {
          articleIndex: i,
          platform: platformId,
          name: PLATFORMS[platformId].name,
          status: 'running',
        });

        try {
          const result = await publishFn(article, options);
          allResults.push(result);
          broadcast('platform', {
            articleIndex: i,
            platform: platformId,
            name: PLATFORMS[platformId].name,
            status: result.success ? 'done' : 'error',
            result,
          });
        } catch (error) {
          // A cancel interrupts the platform's own wait (e.g. login). Don't
          // stamp it as a failure: the user asked it to stop, and the cancelled
          // toast is the truthful account.
          if (signal?.aborted) {
            cancelled = true;
            broadcast('cancelled', {});
            break;
          }
          if (error?.code === 'LOGIN_REQUIRED' && !loginFailed.has(platformId)) {
            loginFailed.add(platformId);
            console.log(`⚠ ${PLATFORMS[platformId].name} 登录未完成，本次运行将跳过该平台剩余稿件`);
          }
          const result = {
            success: false,
            platform: PLATFORMS[platformId].name,
            message: error?.message || String(error),
          };
          allResults.push(result);
          broadcast('platform', {
            articleIndex: i,
            platform: platformId,
            name: PLATFORMS[platformId].name,
            status: 'error',
            result,
          });
        }
      }

      if (cancelled) break;
    }

    if (!cancelled) broadcast('done', { results: allResults });
  } finally {
    isPublishing = false;
    broadcast('status', { publishing: false });
  }

  return allResults;
}

// Content-Security-Policy for the SPA.
//
// `style-src` keeps 'unsafe-inline' because antd (cssinjs) injects <style>
// elements at runtime; that is far less dangerous than an inline-script
// allowance, and `script-src 'self'` stays strict. `img-src` allows http(s)
// because article covers are remote URLs taken from frontmatter. The app is
// same-origin by design, so script/connect/frame are all locked to 'self'.
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https: http:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-src 'none'",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');

